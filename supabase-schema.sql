create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_no text not null unique,
  customer_name text not null,
  email text not null,
  phone text not null,
  address text not null,
  items jsonb not null default '[]'::jsonb,
  subtotal integer not null,
  delivery integer not null default 0,
  total integer not null,
  status integer not null default 0,
  merchant_request_id text,
  checkout_request_id text unique,
  mpesa_receipt text,
  paid_amount numeric,
  paid_phone text,
  mpesa_result_code integer,
  mpesa_result_desc text,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);

create index if not exists orders_order_no_idx on public.orders(order_no);
create index if not exists orders_created_at_idx on public.orders(created_at desc);
-- Keep RLS enabled and do not create public policies for this table.
-- The Node server accesses it with the Supabase service-role key.
alter table public.orders enable row level security;
